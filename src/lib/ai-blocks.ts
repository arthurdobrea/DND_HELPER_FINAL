/** Шаблон «на более высоких кругах». */
export const higherLevelText = (level: number, die: string) =>
  level === 0
    ? `Урон заговора увеличивается на ${die}, когда вы достигаете 5-го уровня, 11-го уровня и 17-го уровня.`
    : `Если вы накладываете это заклинание, используя ячейку ${level + 1}-го круга или выше, урон увеличивается на ${die} за каждый круг ячейки выше ${level}-го.`;

export const fill = (text: string, vars: Record<string, string>) => text.replace(/\{(\w+)\}/g, (m, k: string) => vars[k] ?? m);

