/**
 * Блоки для сборщиков предметов и заклинаний: описание режется на абзацы-блоки («**Заряды.** текст»),
 * блоки можно добавлять из шаблонов, переставлять и править, а затем собрать обратно в текст.
 */
import { rid } from "@/lib/forge";

export type TextBlock = { id: string; title: string; text: string };

/** «**Заряды.** У предмета 7 зарядов» → { title: "Заряды", text: "У предмета 7 зарядов" }. */
export function splitDesc(desc: string): TextBlock[] {
  return String(desc ?? "")
    .replace(/\\n/g, "\n")
    .split(/\n\s*\n|\n/)
    .map((p) => p.trim())
    .filter(Boolean)
    .map((p) => {
      const m = /^\*\*(.+?)\.?\*\*\.?\s*([\s\S]*)$/.exec(p) ?? /^_\*\*(.+?)\.?\*\*_\.?\s*([\s\S]*)$/.exec(p);
      return m ? { id: rid(), title: m[1].trim(), text: m[2].trim() } : { id: rid(), title: "", text: p };
    });
}

export function joinDesc(blocks: TextBlock[]): string {
  return blocks
    .filter((b) => b.title.trim() || b.text.trim())
    .map((b) => (b.title.trim() ? `**${b.title.trim().replace(/\.$/, "")}.** ${b.text.trim()}` : b.text.trim()))
    .join("\n\n");
}

